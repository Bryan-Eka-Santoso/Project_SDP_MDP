const multer = require('multer');
const crypto = require('node:crypto');
const path = require('node:path');
const fs = require('node:fs/promises');
const AppError = require('../../utils/AppError');

const MAX_BYTES = 5 * 1024 * 1024;
const PRIVATE_DIR = path.resolve(__dirname, '../../../private/leave-attachments');
const multipart = multer({
  storage: multer.memoryStorage(),
  limits: { fileSize: MAX_BYTES, files: 1, fields: 4 },
}).single('attachment');

function parseAttachment(req, res, next) {
  if (!req.is('multipart/form-data')) return next();
  multipart(req, res, (err) => {
    if (!err) return next();
    if (err.code === 'LIMIT_FILE_SIZE') return next(new AppError(413, 'FILE_TOO_LARGE', 'Lampiran maksimal 5 MB.'));
    return next(new AppError(400, 'VALIDATION_ERROR', 'Lampiran tidak valid. Gunakan field attachment.'));
  });
}

function fileType(file) {
  if (!file) return null;
  const b = file.buffer;
  const mime = file.mimetype;
  const name = file.originalname.toLowerCase();
  if (name.endsWith('.pdf') && mime === 'application/pdf' && b.subarray(0, 5).toString() === '%PDF-')
    return { extension: '.pdf', mime: 'application/pdf' };
  if (name.endsWith('.png') && mime === 'image/png' && b.length >= 8 && b.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10])))
    return { extension: '.png', mime: 'image/png' };
  if ((name.endsWith('.jpg') || name.endsWith('.jpeg')) && mime === 'image/jpeg' && b.length >= 4 && b[0] === 0xff && b[1] === 0xd8 && b[b.length - 2] === 0xff && b[b.length - 1] === 0xd9)
    return { extension: '.jpg', mime: 'image/jpeg' };
  throw new AppError(415, 'UNSUPPORTED_FILE_TYPE', 'Lampiran harus JPG, PNG, atau PDF yang valid.');
}

async function saveAttachment(file) {
  if (!file) return null;
  const type = fileType(file);
  await fs.mkdir(PRIVATE_DIR, { recursive: true });
  const filename = `${crypto.randomUUID()}${type.extension}`;
  await fs.writeFile(path.join(PRIVATE_DIR, filename), file.buffer, { flag: 'wx', mode: 0o600 });
  return { filename, mime: type.mime };
}

async function deleteAttachment(filename) {
  if (filename) await fs.unlink(path.join(PRIVATE_DIR, filename)).catch(() => {});
}

function absoluteFile(filename) {
  // Only filenames generated by this backend, not arbitrary user-supplied paths.
  if (!/^[a-f0-9-]{36}\.(?:jpg|png|pdf)$/.test(filename))
    throw new AppError(404, 'NOT_FOUND', 'Lampiran tidak ditemukan.');
  return path.join(PRIVATE_DIR, filename);
}

module.exports = { parseAttachment, saveAttachment, deleteAttachment, absoluteFile };
